    private String checkNameFields(){
        HashMap<String, String> fields = new HashMap<>();
        fields.put("First Name", txfFN.getText().trim());
        fields.put("Last Name", txfLN.getText().trim());
        fields.put("Fide ID", txfFID.getText().trim());
        
        return Validation.isValidStrings(fields);
    }
    
    private String checkDoubleFields(){
        HashMap<String, String> fields = new HashMap<>();
        fields.put("Rating", txfRating.getText());
        
        return Validation.isValidNumbers(fields, "double");
    }
    
    private void addPlayer(Player p) {
        if (pe.insert(p)) {

            model.addRow(new Object[]{
                p.getFullName(),
                p.getTitle(),
                p.getFideID(),
                p.getFederation(),
                p.getRating(),
                p.getScore(),
                p.getTieBreak()
            });
            
            System.out.println(p.getFullName() + " has been added to the tournament");
            this.dispose();
        }else {
            System.out.println("Unable to add player to the tournament");
            this.dispose();
        }
    }

