    private void btnValidateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValidateActionPerformed
        String sErrors = checkNameFields(), dErrors = checkDoubleFields(), errors = "";
        
        if(!sErrors.isBlank()) errors += sErrors;
        if(!dErrors.isBlank()) errors += dErrors;
        
        if(errors.isBlank()){
            isValid = true;
            JOptionPane.showMessageDialog(this, "All fields are valid.");
        } else {
            JOptionPane.showMessageDialog(this, errors);
        }
    }//GEN-LAST:event_btnValidateActionPerformed

    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        if (!isValid) {
            String v = "Form is not yet valid/validated.";
            System.out.println(v);
            JOptionPane.showMessageDialog(this, v);
        } else {
            Player p = new Player();
            p.setTournamentID(tID);
            p.setFirstName(txfFN.getText().trim());
            p.setLastName(txfLN.getText().trim());
            p.setFideID(txfFID.getText().trim());
            p.setRating(Double.parseDouble(txfRating.getText().trim()));
            p.setTitle(PlayerTitle.getTitleFromRating(p.getRating()));
            p.setFederation(Federation.getValueFromName((String) cBoxFed.getSelectedItem()).name());
            
            addPlayer(p);
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

